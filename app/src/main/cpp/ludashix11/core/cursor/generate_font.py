#!/usr/bin/env python3
"""Pack the vendored X.Org cursor BDF as static, row-aligned one-bit glyphs."""
import argparse
from pathlib import Path

directory = Path(__file__).resolve().parent
source = directory.parents[1] / "third_party/cursor-font/cursor.bdf"
destination = directory / "font_data.inc"


def generate():
    glyphs = {}
    current = None
    bitmap = False
    for line in source.read_text().splitlines():
        fields = line.split()
        if not fields:
            continue
        if fields[0] == "STARTCHAR":
            current = {"name": fields[1], "rows": []}
        elif fields[0] == "ENCODING":
            current["code"] = int(fields[-1])
        elif fields[0] == "BBX":
            current["box"] = tuple(map(int, fields[1:]))
        elif fields[0] == "BITMAP":
            bitmap = True
        elif fields[0] == "ENDCHAR":
            glyphs[current["code"]] = current
            bitmap = False
        elif bitmap:
            current["rows"].append(bytes.fromhex(line))

    assert set(glyphs) == set(range(154)), "Expected the complete X11 cursor font"
    data, entries = bytearray(), []
    for code in range(154):
        glyph = glyphs[code]
        width, height, left, bottom = glyph["box"]
        assert 0 < width <= 31 and 0 < height <= 31
        assert len(glyph["rows"]) == height
        assert all(len(row) == (width + 7) // 8 for row in glyph["rows"])
        pixels = b"".join(glyph["rows"])
        entries.append(
            f"    {{{{fontBitmap + {len(data)}, {len(pixels)}}}, "
            f"{width}, {height}, {left}, {-height - bottom}}}, // {code} {glyph['name']}"
        )
        data.extend(pixels)

    output = [
        "// Generated by generate_font.py from the X.Org cursor font.",
        "// See third_party/cursor-font/COPYING and SOURCE.",
        "constexpr uint8_t fontBitmap[] = {",
    ]
    for offset in range(0, len(data), 16):
        output.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ",")
    output += ["};", "", "constexpr CursorGlyph glyphs[] = {", *entries, "};", ""]
    return "\n".join(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if destination.read_text() != content:
            raise SystemExit("font_data.inc differs from the upstream BDF")
    else:
        destination.write_text(content)
